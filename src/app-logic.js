export function getLocalizedText(language, key) {
  return uiText[language]?.[key] ?? uiText.pl[key] ?? key;
}

export function translateClass(className, language) {
  return translations[className]?.[language] || className || getLocalizedText(language, "unknown");
}

export function sortPredictionsByScore(predictions) {
  return [...predictions].sort((a, b) => b.score - a.score);
}

export function getTopPredictions(predictions, limit = 2) {
  return sortPredictionsByScore(predictions).slice(0, limit);
}

export function filterPredictionsByScore(predictions, minimumScore = 0.5) {
  return predictions.filter((prediction) => prediction.score >= minimumScore);
}

export function formatPredictionScore(score) {
  return `${Math.round(score * 100)}%`;
}
